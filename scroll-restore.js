// Гарантирует, что каждая полная загрузка страницы (F5, Ctrl+F5, повторное
// открытие, а также восстановление из bfcache кнопками "назад"/"вперёд")
// начинается сверху — а не с той позиции, на которой был закрыт/обновлён
// предыдущий раз.
//
// history.scrollRestoration="manual" здесь НЕ ставим — это сделано инлайн-скриптом
// в самом начале <head> каждой страницы, ДО тега CSP (см. комментарий там: у
// meta-CSP есть особенность — она не действует на то, что идёт в документе перед
// ней). Этому файлу, как внешнему, для загрузки нужен поход в сеть — то есть
// лишняя задержка, которой при reload/Ctrl+Shift+R браузеру достаточно, чтобы
// успеть восстановить старую позицию скролла раньше, чем мы её отключим. Инлайн
// этой задержки не имеет. А вот то, что ниже (слушатель pageshow), торопиться
// уже не обязано — он просто должен быть повешен раньше, чем событие наступит,
// с этим внешний файл справляется одинаково хорошо что инлайн, что нет.
//
// pageshow, а не load: load не срабатывает при восстановлении страницы из
// bfcache, а pageshow срабатывает и при обычной загрузке, и при этом —
// в обоих случаях страница должна оказаться наверху.
window.addEventListener("pageshow", () => {
  // На сайте есть ссылки-якоря (href="#catalog" и т.п.) — если адрес остался
  // в URL с прошлого раза (например, кликнули "Смотреть каталог", потом
  // обновили страницу), браузер САМ прокручивает к этому месту при загрузке —
  // и продолжает подправлять прокрутку к нему по ходу дела, пока догружаются
  // картинки и меняется вёрстка (это его штатное поведение для якорей, не баг).
  // Из-за html{scroll-behavior:smooth} в CSS это ещё и выглядит как плавное
  // "сползание" вниз уже ПОСЛЕ того, как страницу вернули наверх. Убираем hash
  // из адресной строки — тогда браузеру просто нечего больше доскролливать.
  // Сами якорные ссылки продолжают работать как обычно: это трогает только URL,
  // с которым страница ЗАГРУЗИЛАСЬ, а не клики по ссылкам после.
  if (location.hash) {
    history.replaceState(null, "", location.pathname + location.search);
  }
  window.scrollTo(0, 0);
});
